pub(super) fn log_step_1(index: usize) -> DyadicFloat128 {
    // For 1 <= i <= 126, r = ceil(32640 / (128 + i)) / 256, so -log(r)
    // is nondecreasing. With y = (1 - r) / (1 + r), its exact value lies
    // between L = 2(y + y^3/3) and U = L + 2*y^5/(5*(1 - y^2)),
    // by the series for log((1 + y)/(1 - y)).
    // Substitution gives U(r[i-1]) < 2^k <= L(r[i]) for
    // (i,k) = (1,-7), (2,-6), (4,-5), (8,-4), (18,-3), (37,-2), (83,-1).
    // Here r[0] = 1 and U(r[126]) < 1. The endpoint gaps exceed 2^-16,
    // so rounding to 128 bits preserves these binades. The stored exponent
    // for a binade starting at 2^k is k - 127.
    let exponent = match index {
        0 | 127 => 0,
        1 => -134,
        2..=3 => -133,
        4..=7 => -132,
        8..=17 => -131,
        18..=36 => -130,
        37..=82 => -129,
        _ => -128,
    };
    DyadicFloat128 {
        sign: DyadicSign::Pos,
        exponent,
        mantissa: LOG_STEP_1[index],
    }
}

